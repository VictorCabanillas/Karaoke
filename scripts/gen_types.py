"""Generate web/shared/types.ts from the Pydantic models (JSON Schema -> json-schema-to-typescript).

Usage: uv run python scripts/gen_types.py   (or: npm run gen:types)
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from pydantic import BaseModel, TypeAdapter  # noqa: E402
from pydantic.json_schema import models_json_schema  # noqa: E402

from server import models  # noqa: E402

SCHEMA_OUT = ROOT / "web" / "shared" / "schema.json"
TYPES_OUT = ROOT / "web" / "shared" / "types.ts"


def exported_models() -> list[type[BaseModel]]:
    return [
        obj
        for obj in vars(models).values()
        if isinstance(obj, type)
        and issubclass(obj, models.Model)
        and obj not in (models.Model, models.InputModel)
        and obj.__module__ == models.__name__
    ]


def _clean(node, aliases: dict[str, dict], top: bool = False):
    """Drop per-field titles (they become noisy TS aliases) and point enums/unions at named aliases."""
    if isinstance(node, list):
        return [_clean(n, aliases) for n in node]
    if not isinstance(node, dict):
        return node
    if not top:
        core = {k: v for k, v in node.items() if k not in ("title", "default", "description")}
        for name, alias in aliases.items():
            if core == alias:
                return {"$ref": f"#/$defs/{name}"}
    out = {}
    for key, value in node.items():
        if key == "title" and not top:
            continue
        if key == "properties":
            out[key] = {k: _clean(v, aliases) for k, v in value.items()}
        else:
            out[key] = _clean(value, aliases)
    return out


def build_schema() -> dict:
    # Input-only models keep their defaults optional; everything else is described as the server sends it.
    pairs = [(m, "validation" if issubclass(m, models.InputModel) else "serialization") for m in exported_models()]
    _, schema = models_json_schema(pairs, title="KaraokeTypes")
    defs = schema.setdefault("$defs", {})
    aliases: dict[str, dict] = {}
    for name in getattr(models, "TS_ALIASES", ()):
        alias_schema = TypeAdapter(getattr(models, name)).json_schema(
            ref_template="#/$defs/{model}", mode="serialization"
        )
        alias_schema.pop("$defs", None)
        alias_schema.pop("title", None)
        aliases[name] = alias_schema
    cleaned = {name: _clean(d, aliases, top=True) for name, d in defs.items()}
    for name, alias in aliases.items():
        cleaned[name] = {**_clean(alias, {k: v for k, v in aliases.items() if k != name}), "title": name}
    schema["$defs"] = cleaned
    return schema


def main() -> None:
    schema = build_schema()
    SCHEMA_OUT.write_text(json.dumps(schema, indent=2, ensure_ascii=False), encoding="utf-8")
    json2ts = shutil.which("json2ts", path=str(ROOT / "node_modules" / ".bin"))
    if not json2ts:
        sys.exit("json2ts not found: run `npm install` first")
    subprocess.run(
        [
            json2ts,
            "--input", str(SCHEMA_OUT),
            "--output", str(TYPES_OUT),
            "--unreachableDefinitions",
            "--no-additionalProperties",
            "--bannerComment", "/* Generated by scripts/gen_types.py from server/models.py. Do not edit. */",
        ],
        check=True,
    )  # fmt: skip
    print(f"Wrote {TYPES_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
